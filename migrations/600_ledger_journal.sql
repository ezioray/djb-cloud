-- 600 · M06 账本 · 凭证头 / 凭证行（journal_entry · journal_line）与只追加护栏
-- 规格：product/v4/modules/M06-ledger.md §3 不变量 / §5 数据所有权 / §8.2 常量
--       product/v4/src/20-payment-ledger.md §20.2 科目表 · §20.3.1 E1–E17 · §20.4.2 B1/B4 · §20.4.3 R7/R9
-- 常量：03-facts §6（42 科目 / E1–E17 / 整数最小单位 / 不 UPDATE-DELETE）；M06 §8.2 JOURNAL_MAX_LINES=64
--
-- 原则：
--   1) 只加不改：只建 M06 的新表/新函数，001–006 的对象与数据零改动，不写任何账本分录。
--   2) 只追加（INV-08）：journal_line 拒绝 UPDATE/DELETE；journal_entry 只允许冲正所需的
--      status posted → voided（且除 status 外任何列不得变化），其余 UPDATE/DELETE 一律拒绝。
--   3) 借贷平衡（INV-01 / B1）：提交时刻（DEFERRABLE 约束触发器）校验 Σ借 = Σ贷 > 0、行数 2..64。
--   4) 单位内平衡（INV-04）：unit_type 只在凭证头上，行不携带单位 → 跨单位混记结构上不可表达。
--   5) 幂等键（INV-06 / I-8）：UNIQUE(source_type, source_id, event_seq)，重复请求返回既有凭证（T2）。
--   6) 可重复执行：IF NOT EXISTS / DROP ... IF EXISTS + CREATE / CREATE OR REPLACE；
--      末尾结构断言保证「已存在的表」与本节定义同形，避免半途建表被静默放过。
BEGIN;

-- ────────────────────────────────────────────── 只追加护栏（INV-08，本段所有表共用）
-- 严格版：任何 UPDATE / DELETE 直接报错（SQLSTATE 42501）。journal_line / account_balances /
-- merkle_commitments 使用；错误信息保留 "append-only" 字样，便于运维与日志检索。
CREATE OR REPLACE FUNCTION m06_forbid_mutation() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is append-only: % not allowed (INV-08)', TG_TABLE_NAME, TG_OP
    USING ERRCODE = '42501';
END;
$$ LANGUAGE plpgsql;

-- TRUNCATE 绕过行级触发器（005 同款处理）：只追加表必须用语句级触发器单独拦，否则一条
-- TRUNCATE 就能把账本清空而 UPDATE/DELETE 护栏毫无反应。
CREATE OR REPLACE FUNCTION m06_forbid_truncate() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is append-only: TRUNCATE not allowed (INV-08)', TG_TABLE_NAME
    USING ERRCODE = '42501';
END;
$$ LANGUAGE plpgsql;

-- 宽松版：只放行「冲正」所需的唯一迁移 status posted → voided（INV-07），其余照旧拒绝。
-- 除 status 之外的列只要有一处不同就拒绝（覆盖金额、科目、幂等键等一切业务字段）。
CREATE OR REPLACE FUNCTION m06_allow_void_only() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION '% is append-only: DELETE not allowed (INV-08)', TG_TABLE_NAME
      USING ERRCODE = '42501';
  END IF;
  -- 先判「除 status 外是否动过」：动过就是硬违规，与状态是否迁移无关（信息更准确）
  IF (to_jsonb(NEW) - 'status') IS DISTINCT FROM (to_jsonb(OLD) - 'status') THEN
    RAISE EXCEPTION '% is append-only: only status may change (INV-08)', TG_TABLE_NAME
      USING ERRCODE = '42501';
  END IF;
  -- 再判状态迁移方向：posted -> voided 是冲正唯一合法的迁移（INV-07）
  IF NOT (OLD.status = 'posted' AND NEW.status = 'voided') THEN
    RAISE EXCEPTION '% only allows posted -> voided (reversal), got % -> % (INV-07)',
      TG_TABLE_NAME, OLD.status, NEW.status
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ────────────────────────────────────────────────────────────── 凭证头（一次资金事件一条）
-- 与 §20.4.2 的差异只有「加」：event_type（E1–E17 白名单，journal.posted 需要）、seq（链序）、
-- status（R7 两态）；单位只在本表出现，行上没有 unit_type（INV-04）。
CREATE TABLE IF NOT EXISTS journal_entry (
  journal_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  seq                BIGINT GENERATED BY DEFAULT AS IDENTITY,     -- 链序：读 prev_hash / Merkle 区间用
  ts                 TIMESTAMPTZ NOT NULL,                        -- 事实发生时间（UTC）
  event_type         TEXT NOT NULL,                               -- E1–E17（§20.3.1）
  unit_type          TEXT NOT NULL,                               -- USD / COP / STABLE_USDT / FIAT_CNY
  source_type        TEXT NOT NULL,                               -- 16 值白名单（spec SourceType / 04 契约）
  source_id          TEXT NOT NULL,
  event_seq          SMALLINT NOT NULL DEFAULT 0,
  policy_version     TEXT NOT NULL,                               -- 费率 / 汇率 / 确认数口径版本（R10）
  fx_rate_id         BIGINT NOT NULL DEFAULT 1 CHECK (fx_rate_id > 0),  -- 1 = 同币种无换汇（CR-L2 后接 fx_rate）
  approval_chain     JSONB,                                       -- 双人复核轨迹（T3 冲正用，INV-07）
  merkle_period      TEXT,                                        -- 归属期间（journal / daily_close 根，INV-13）
  reversal_of_journal UUID REFERENCES journal_entry(journal_id),   -- 冲正指向原凭证（INV-07 / R5）
  status             TEXT NOT NULL DEFAULT 'posted',
  prev_hash          BYTEA,                                       -- 链首为 NULL（GENESIS）
  hash               BYTEA NOT NULL,                              -- sha256(prev_hash ‖ canonical(row))
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT journal_entry_event_type_ck CHECK (
    event_type IN ('E1','E2','E3','E4','E5','E6','E7','E8','E9','E10','E11','E12','E13','E14','E15','E16','E17')
  ),
  CONSTRAINT journal_entry_unit_type_ck CHECK (
    unit_type IN ('USD', 'COP', 'STABLE_USDT', 'FIAT_CNY')
  ),
  CONSTRAINT journal_entry_source_type_ck CHECK (
    source_type IN ('chain_tx','payment_attempt','conversion_trade','usage_settle','lock_expiry',
                    'payout_accrual','payout_item','payout_batch','wallet_transfer','refund',
                    'chargeback','rebate','fx_reval','loss_pool','void','unidentified')
  ),
  CONSTRAINT journal_entry_source_id_ck CHECK (length(source_id) BETWEEN 1 AND 128),
  CONSTRAINT journal_entry_event_seq_ck CHECK (event_seq >= 0),
  CONSTRAINT journal_entry_policy_version_ck CHECK (length(policy_version) BETWEEN 1 AND 64),
  CONSTRAINT journal_entry_status_ck CHECK (status IN ('posted', 'voided')),
  CONSTRAINT journal_entry_prev_hash_ck CHECK (prev_hash IS NULL OR octet_length(prev_hash) = 32),
  CONSTRAINT journal_entry_hash_ck CHECK (octet_length(hash) = 32),
  CONSTRAINT journal_entry_no_self_reversal_ck CHECK (
    reversal_of_journal IS NULL OR reversal_of_journal <> journal_id
  ),
  CONSTRAINT journal_entry_seq_uq UNIQUE (seq),
  -- INV-06 / I-8：幂等键唯一。重复请求由 T2 读既有凭证返回，不重复落账。
  CONSTRAINT journal_entry_idem_uq UNIQUE (source_type, source_id, event_seq),
  -- 链分叉护栏：同一 hash 不可能出现两条（prev_hash 决定后继，重复即分叉）
  CONSTRAINT journal_entry_hash_uq UNIQUE (hash),
  -- 供 ledger_entry 的复合外键使用：分录与凭证必须同单位（INV-04）
  CONSTRAINT journal_entry_journal_unit_uq UNIQUE (journal_id, unit_type)
);

-- 每原凭证至多一条冲正（INV-07）；冲正凭证自身也受本索引保护（不可被再次冲正两次）
CREATE UNIQUE INDEX IF NOT EXISTS journal_entry_reversal_uq
  ON journal_entry (reversal_of_journal) WHERE reversal_of_journal IS NOT NULL;
CREATE INDEX IF NOT EXISTS journal_entry_ts_idx ON journal_entry (ts);
CREATE INDEX IF NOT EXISTS journal_entry_merkle_period_idx
  ON journal_entry (merkle_period) WHERE merkle_period IS NOT NULL;

DROP TRIGGER IF EXISTS journal_entry_no_mutation ON journal_entry;
CREATE TRIGGER journal_entry_no_mutation BEFORE UPDATE OR DELETE ON journal_entry
  FOR EACH ROW EXECUTE FUNCTION m06_allow_void_only();
DROP TRIGGER IF EXISTS journal_entry_no_truncate ON journal_entry;
CREATE TRIGGER journal_entry_no_truncate BEFORE TRUNCATE ON journal_entry
  FOR EACH STATEMENT EXECUTE FUNCTION m06_forbid_truncate();

-- ────────────────────────────────────────────────────────────── 凭证行（会计视角，一行一科目）

CREATE TABLE IF NOT EXISTS journal_line (
  line_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id     UUID NOT NULL REFERENCES journal_entry(journal_id),
  line_no        SMALLINT NOT NULL,
  -- 1:1 指向 ledger_entry（INV-02）；外键在 601 建（ledger_entry 先于本节创建顺序之外）
  ledger_entry_id UUID NOT NULL,
  account_id     TEXT NOT NULL,          -- 科目账户 / 主体账户（accounts 归 M01：软引用，不跨模块建 FK）
  coa_code       TEXT NOT NULL,          -- 42 科目白名单（INV-03）
  dc             CHAR(1) NOT NULL,       -- D 借 / C 贷
  amount_minor   BIGINT NOT NULL,        -- 整数最小单位（USD micro），借贷平衡只看本列
  unit_scale     SMALLINT NOT NULL DEFAULT 6,
  amount         NUMERIC GENERATED ALWAYS AS (amount_minor::numeric / power(10::numeric, unit_scale)) STORED,
  qty_minor      BIGINT,                 -- 资产行辅助计量（INV-11 / R4）
  fund_class     TEXT NOT NULL,          -- CLIENT / PLATFORM / FEE，须与科目归属一致（INV-03）
  wallet_id      TEXT,                   -- 软引用 wallet.wallet_id（wallet 归 M08，不建 FK）

  CONSTRAINT journal_line_line_no_ck CHECK (line_no BETWEEN 1 AND 64),        -- JOURNAL_MAX_LINES
  CONSTRAINT journal_line_dc_ck CHECK (dc IN ('D', 'C')),
  CONSTRAINT journal_line_amount_ck CHECK (amount_minor > 0),
  CONSTRAINT journal_line_unit_scale_ck CHECK (unit_scale BETWEEN 0 AND 18),
  CONSTRAINT journal_line_qty_ck CHECK (qty_minor IS NULL OR qty_minor > 0),
  CONSTRAINT journal_line_fund_class_ck CHECK (fund_class IN ('CLIENT', 'PLATFORM', 'FEE')),
  -- INV-03 前半：42 科目白名单（12 资产 / 12 负债与权益 / 6 收入 / 10 费用与损失 / 2 非现金与调整）
  CONSTRAINT journal_line_coa_ck CHECK (coa_code IN (
    '1101','1102','1103','1109','1111','1120','1121','1130','1140','1190','1901','1910',
    '2101','2102','2103','2201','2202','2203','2204','2210','2301','2901','2990','3101',
    '4101','4102','4103','4104','4105','4201',
    '5101','5102','5103','5104','5105','5106','5201','5301','5401','5501',
    '6101','6901'
  )),
  -- INV-03 后半：fund_class 与科目归属一致（§20.2.2–§20.2.6）
  CONSTRAINT journal_line_coa_fund_class_ck CHECK (
    (fund_class = 'CLIENT' AND coa_code IN (
      '1101','1102','1103','1111','1120','1121','1130','1190','1901','1910',
      '2101','2102','2103','2201','2202','2203','2204','2210','2301','2990'))
    OR (fund_class = 'PLATFORM' AND coa_code IN ('1109','1140','3101'))
    OR (fund_class = 'FEE' AND coa_code IN (
      '2901','4101','4102','4103','4104','4105','4201',
      '5101','5102','5103','5104','5105','5106','5201','5301','5401','5501','6101','6901'))
  ),
  -- INV-11 / C4：链上资产双记，1101/1102/1103 必须同时给 qty_minor
  CONSTRAINT journal_line_asset_qty_ck CHECK (
    coa_code NOT IN ('1101','1102','1103') OR qty_minor IS NOT NULL
  ),
  CONSTRAINT journal_line_journal_line_uq UNIQUE (journal_id, line_no),
  -- INV-02：每行 1:1 一条 ledger_entry（跨凭证重复引用同样被拒绝）
  CONSTRAINT journal_line_ledger_entry_uq UNIQUE (ledger_entry_id)
);

CREATE INDEX IF NOT EXISTS journal_line_coa_ts_idx ON journal_line (coa_code, journal_id);
CREATE INDEX IF NOT EXISTS journal_line_account_idx ON journal_line (account_id);

DROP TRIGGER IF EXISTS journal_line_no_mutation ON journal_line;
CREATE TRIGGER journal_line_no_mutation BEFORE UPDATE OR DELETE ON journal_line
  FOR EACH ROW EXECUTE FUNCTION m06_forbid_mutation();
DROP TRIGGER IF EXISTS journal_line_no_truncate ON journal_line;
CREATE TRIGGER journal_line_no_truncate BEFORE TRUNCATE ON journal_line
  FOR EACH STATEMENT EXECUTE FUNCTION m06_forbid_truncate();

-- 行只能挂在 posted 凭证上：voided 凭证不得再补行（冲正走新凭证，INV-07）
CREATE OR REPLACE FUNCTION m06_journal_line_open_trg() RETURNS trigger AS $$
DECLARE
  v_status TEXT;
BEGIN
  SELECT status INTO v_status FROM journal_entry WHERE journal_id = NEW.journal_id;
  IF v_status IS NULL THEN
    RAISE EXCEPTION 'journal_line: journal % not found', NEW.journal_id USING ERRCODE = '23503';
  END IF;
  IF v_status <> 'posted' THEN
    RAISE EXCEPTION 'journal_line: journal % is %, cannot append lines (INV-07)', NEW.journal_id, v_status
      USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS journal_line_open_journal ON journal_line;
CREATE TRIGGER journal_line_open_journal BEFORE INSERT ON journal_line
  FOR EACH ROW EXECUTE FUNCTION m06_journal_line_open_trg();

-- ────────────────────────────────────────────── 借贷平衡（INV-01 / B1）：提交时校验
CREATE OR REPLACE FUNCTION m06_assert_journal_balanced(p_journal_id UUID) RETURNS void AS $$
DECLARE
  v_lines   INT;
  v_debit   BIGINT;
  v_credit  BIGINT;
BEGIN
  SELECT count(*),
         COALESCE(sum(amount_minor) FILTER (WHERE dc = 'D'), 0),
         COALESCE(sum(amount_minor) FILTER (WHERE dc = 'C'), 0)
    INTO v_lines, v_debit, v_credit
    FROM journal_line WHERE journal_id = p_journal_id;

  IF v_lines < 2 THEN
    RAISE EXCEPTION 'journal % has % line(s): at least 2 required (INV-01)', p_journal_id, v_lines
      USING ERRCODE = '23514';
  END IF;
  IF v_lines > 64 THEN
    RAISE EXCEPTION 'journal % has % lines: max 64 (JOURNAL_MAX_LINES)', p_journal_id, v_lines
      USING ERRCODE = '23514';
  END IF;
  IF v_debit <> v_credit THEN
    RAISE EXCEPTION 'journal % is not balanced: debit=% credit=% (INV-01)', p_journal_id, v_debit, v_credit
      USING ERRCODE = '23514';
  END IF;
  IF v_debit <= 0 THEN
    RAISE EXCEPTION 'journal % total amount must be > 0 (INV-01)', p_journal_id
      USING ERRCODE = '23514';
  END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION m06_journal_balanced_trg() RETURNS trigger AS $$
BEGIN
  PERFORM m06_assert_journal_balanced(NEW.journal_id);
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- 约束触发器延迟到事务提交：T2 可以在同一事务内先写凭证头、再写行（§6 事务边界）
DROP TRIGGER IF EXISTS journal_entry_balanced ON journal_entry;
CREATE CONSTRAINT TRIGGER journal_entry_balanced AFTER INSERT ON journal_entry
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION m06_journal_balanced_trg();

-- ────────────────────────────────────────────── 结构断言（已存在的表必须与本文件同形）
DO $$
DECLARE
  v_missing TEXT;
BEGIN
  SELECT string_agg(c, ', ') INTO v_missing
    FROM unnest(ARRAY['journal_id','seq','ts','event_type','unit_type','source_type','source_id',
                      'event_seq','policy_version','fx_rate_id','approval_chain','merkle_period',
                      'reversal_of_journal','status','prev_hash','hash','created_at']) AS c
   WHERE NOT EXISTS (
     SELECT 1 FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = 'journal_entry' AND column_name = c);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION 'journal_entry 结构与 600 不符，缺列：%', v_missing;
  END IF;

  SELECT string_agg(c, ', ') INTO v_missing
    FROM unnest(ARRAY['line_id','journal_id','line_no','ledger_entry_id','account_id','coa_code','dc',
                      'amount_minor','unit_scale','amount','qty_minor','fund_class','wallet_id']) AS c
   WHERE NOT EXISTS (
     SELECT 1 FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = 'journal_line' AND column_name = c);
  IF v_missing IS NOT NULL THEN
    RAISE EXCEPTION 'journal_line 结构与 600 不符，缺列：%', v_missing;
  END IF;
END;
$$;

